#!/usr/bin/env bash
# Shared dev infrastructure + per-worktree isolation. Called from the justfile
# (`just infra-up`, `just wt-up`, …) with the checkout's .envrc loaded; see
# docs/worktrees.md for the model this implements.
set -euo pipefail

die() { echo "error: $*" >&2; exit 1; }
warn() { echo "warning: $*" >&2; }
step() { printf '\n==> %s\n' "$*"; }

[ -n "${LC_WT:-}" ] || die "LC_WT is unset; run this inside the checkout with direnv loaded (direnv allow)"

checkout_root=$(git rev-parse --show-toplevel)

# The infra stack always runs from the primary checkout so its bind mounts
# (etc/postgres-init, etc/temporal/…) never point into a worktree that gets
# deleted. Until the primary checkout's branch has docker-compose.infra.yml,
# fall back to this checkout's copy.
if [ -f "$LC_MAIN_ROOT/docker-compose.infra.yml" ]; then
  infra_dir=$LC_MAIN_ROOT
else
  infra_dir=$checkout_root
  warn "$LC_MAIN_ROOT has no docker-compose.infra.yml yet; running infra from $infra_dir"
fi

infra() {
  local dir=$infra_dir
  # COMPOSE_FILE/COMPOSE_PROFILES describe this checkout's APP stack; keep them
  # away from the infra project.
  COMPOSE_FILE='' COMPOSE_PROFILES='' \
    docker compose -p lc-infra --project-directory "$dir" -f "$dir/docker-compose.infra.yml" "$@"
}

app() { docker compose "$@"; }

psql_admin() {
  infra exec -T postgres psql -v ON_ERROR_STOP=1 -U "$PG_USER" -d postgres -Atq "$@"
}

db_exists() {
  [ "$(psql_admin -c "SELECT 1 FROM pg_database WHERE datname = '$1'")" = 1 ]
}

os() {
  local path=$1
  shift
  curl -sS -f -H 'Content-Type: application/json' "$HOST_OPENSEARCH_URL$path" "$@"
}

require_worktree() {
  [ "$LC_WT" != main ] || die "this is the primary checkout; use \`just up\` / \`just stop\` here"
}

# Worktree prefixes always end in `__`; refuse anything else before deleting.
require_safe_prefix() {
  case "$OPENSEARCH_INDEX_PREFIX" in
    ?*__) ;;
    *) die "refusing to touch indices for OPENSEARCH_INDEX_PREFIX='$OPENSEARCH_INDEX_PREFIX'" ;;
  esac
}

wait_healthy() {
  local service id status deadline=$((SECONDS + 300))
  for service in "$@"; do
    printf 'waiting for %s' "$service"
    until id=$(infra ps -q "$service") && [ -n "$id" ] &&
      status=$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$id") &&
      { [ "$status" = healthy ] || [ "$status" = running ]; }; do
      [ "$SECONDS" -lt "$deadline" ] || die "$service did not become healthy"
      printf '.'
      sleep 2
    done
    echo " ok"
  done
}

#
# Certificates
#

traefik_dir() { echo "$LC_DEV_HOME/traefik"; }

# Writes <name>.pem/-key.pem plus a Traefik dynamic-config <name>.yml that
# registers them. Regenerated only when the SAN list changes.
issue_cert() {
  local name=$1
  shift
  local dir sans
  dir=$(traefik_dir)
  sans="$*"
  command -v mkcert >/dev/null || die "mkcert not found (it ships in shell.nix; is direnv loaded?)"
  mkdir -p "$dir"
  if [ -f "$dir/$name.pem" ] && [ "$(cat "$dir/$name.sans" 2>/dev/null)" = "$sans" ]; then
    return
  fi
  mkcert -cert-file "$dir/$name.pem" -key-file "$dir/$name-key.pem" "$@" >/dev/null 2>&1 ||
    die "mkcert failed for $name"
  echo "$sans" >"$dir/$name.sans"
  cat >"$dir/$name.yml" <<EOF
# Generated by scripts/dev-env.sh for: $sans
tls:
  certificates:
    - certFile: /etc/traefik/dynamic/$name.pem
      keyFile: /etc/traefik/dynamic/$name-key.pem
EOF
  echo "issued certificate $name: $sans"
}

check_ca_trusted() {
  local ca
  ca="$(mkcert -CAROOT)/rootCA.pem"
  if [ ! -f "$ca" ]; then
    warn "no mkcert CA yet; run \`mkcert -install\` once (asks for your password), then \`just wt-cert\`"
  elif [ "$(uname)" = Darwin ] && ! security verify-cert -c "$ca" >/dev/null 2>&1; then
    warn "the mkcert CA isn't trusted by macOS; run \`mkcert -install\` once (asks for your password)"
  fi
}

cmd_cert() {
  issue_cert infra 'infra.localhost' '*.infra.localhost'
  issue_cert "wt-$LC_WT" "$LC_WEB_HOST" "*.$LC_WEB_HOST" "$LC_LB_HOST" \
    "$LC_WT.storybook.localhost" "$LC_WT.storybook-lb.localhost"
  check_ca_trusted
}

#
# Shared infrastructure
#

cmd_infra_up() {
  # Two Postgres containers on one data volume corrupt it. The pre-split stack
  # (`letschurch_dev`) ran Postgres itself; make sure it's gone first.
  local pg_volume=${LC_INFRA_PG_VOLUME:-letschurch_dev_pg-data} id project
  for id in $(docker ps -aq --filter "volume=$pg_volume"); do
    project=$(docker inspect -f '{{index .Config.Labels "com.docker.compose.project"}}' "$id")
    [ "$project" = lc-infra ] ||
      die "container $(docker inspect -f '{{.Name}}' "$id") (project '$project') still uses $pg_volume. Remove the old stack first: \`docker compose -p $project down\` (data volumes are kept)."
  done
  cmd_cert
  infra up -d --remove-orphans "$@"
  wait_healthy postgres opensearch valkey temporal
}

#
# Per-worktree provisioning
#

# Copy a database from the primary checkout's (instant-ish and keeps all its
# data), or create an empty one. CREATE DATABASE … TEMPLATE needs the source to
# have no connections, so the primary checkout's app is cut off for the few
# seconds the copy takes; its connection pool reconnects on its own.
provision_db() {
  local src=$1 dst=$2 mode=$3 rc=0
  if db_exists "$dst"; then
    echo "database $dst exists"
    return
  fi
  if [ "$mode" = fresh ] || ! db_exists "$src"; then
    psql_admin -c "CREATE DATABASE \"$dst\""
    echo "created empty database $dst"
    return
  fi
  echo "copying database $src -> $dst"
  psql_admin -c "ALTER DATABASE \"$src\" ALLOW_CONNECTIONS false"
  psql_admin -c "SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = '$src' AND pid <> pg_backend_pid()" >/dev/null &&
    psql_admin -c "CREATE DATABASE \"$dst\" TEMPLATE \"$src\" STRATEGY FILE_COPY" || rc=$?
  psql_admin -c "ALTER DATABASE \"$src\" ALLOW_CONNECTIONS true"
  [ "$rc" = 0 ] || die "copying $src failed"
}

provision_dbs() {
  local mode=$1
  provision_db letschurch "$LC_PG_DATABASE" "$mode"
  provision_db letsbible "$LC_LB_PG_DATABASE" "$mode"
  # Database-level grants aren't part of the template copy (see
  # etc/postgres-init/lets-bible.sql).
  psql_admin -c "GRANT ALL PRIVILEGES ON DATABASE \"$LC_LB_PG_DATABASE\" TO letsbible"
  infra exec -T postgres psql -v ON_ERROR_STOP=1 -U "$PG_USER" -d "$LC_LB_PG_DATABASE" -q \
    -c 'GRANT ALL ON SCHEMA public TO letsbible'
}

# Clone every primary-checkout index (`lc_*`, `lets_bible_*`) under this
# worktree's prefix. The _clone API hard-links segments, so it's fast and cheap
# on disk, but needs the source write-blocked for the moment it takes. Search
# pipelines aren't cloned; `just os-push-mappings` / `lb-es-push` create them.
clone_indices() {
  require_safe_prefix
  local idx dst rc
  for idx in $(os '/_cat/indices/lc_*,lets_bible_*?h=index&expand_wildcards=open' | tr -d ' ' | grep -v '__' | sort); do
    dst=$OPENSEARCH_INDEX_PREFIX$idx
    if os "/$dst" -o /dev/null -I 2>/dev/null; then
      echo "index $dst exists"
      continue
    fi
    echo "cloning index $idx -> $dst"
    rc=0
    os "/$idx/_settings" -X PUT -d '{"index.blocks.write": true}' >/dev/null
    os "/$idx/_clone/$dst" -X POST >/dev/null || rc=$?
    os "/$idx/_settings" -X PUT -d '{"index.blocks.write": null}' >/dev/null
    [ "$rc" = 0 ] || die "cloning $idx failed"
    os "/_cluster/health/$dst?wait_for_status=yellow&timeout=120s" >/dev/null
    os "/$dst/_settings" -X PUT -d '{"index.blocks.write": null}' >/dev/null
  done
}

cmd_wt_up() {
  require_worktree
  local mode=${1:-clone}
  case "$mode" in clone | fresh) ;; *) die "usage: just wt-up [clone|fresh]" ;; esac

  step "Shared infrastructure + certificates"
  cmd_infra_up
  step "Databases ($mode)"
  provision_dbs "$mode"
  if [ "$mode" = clone ]; then
    step "Search indices"
    clone_indices
  fi
  step "App containers ($COMPOSE_PROJECT_NAME)"
  app up -d --build --remove-orphans
  step "Migrations, mappings, schedules"
  just init lb-migrate lb-es-push lb-flex
  if [ "$mode" = fresh ]; then
    step "Seed"
    just seed-db lb-up
  fi
  cmd_wt_info
}

cmd_wt_down() {
  require_worktree
  require_safe_prefix

  step "App containers ($COMPOSE_PROJECT_NAME)"
  app --profile '*' down --volumes --remove-orphans

  if [ -z "$(infra ps -q postgres 2>/dev/null)" ]; then
    warn "shared infrastructure isn't running; starting it to clean up"
    cmd_infra_up
  fi

  step "Databases"
  psql_admin -c "DROP DATABASE IF EXISTS \"$LC_PG_DATABASE\" WITH (FORCE)"
  psql_admin -c "DROP DATABASE IF EXISTS \"$LC_LB_PG_DATABASE\" WITH (FORCE)"

  step "Search indices + pipelines ($OPENSEARCH_INDEX_PREFIX*)"
  local idx pipeline
  for idx in $(os "/_cat/indices/${OPENSEARCH_INDEX_PREFIX}*?h=index&expand_wildcards=all" | tr -d ' '); do
    os "/$idx" -X DELETE >/dev/null && echo "deleted $idx"
  done
  for pipeline in lc-media-rrf lets_bible_hybrid; do
    os "/_search/pipeline/$OPENSEARCH_INDEX_PREFIX$pipeline" -X DELETE >/dev/null 2>&1 || true
  done

  step "Temporal namespace $TEMPORAL_NAMESPACE"
  infra exec -T temporal-admin-tools temporal operator namespace delete \
    --namespace "$TEMPORAL_NAMESPACE" --yes ||
    warn "couldn't delete namespace $TEMPORAL_NAMESPACE"

  step "Valkey DB $LC_VALKEY_DB"
  infra exec -T valkey valkey-cli -n "$LC_VALKEY_DB" FLUSHDB >/dev/null

  step "Certificate"
  rm -f "$(traefik_dir)/wt-$LC_WT".{pem,yml,sans} "$(traefik_dir)/wt-$LC_WT-key.pem"
  echo "removed wt-$LC_WT"
}

cmd_wt_info() {
  local web=$HOST_WEB_URL lb=$HOST_LETS_BIBLE_URL
  cat <<EOF

$LC_WT ($COMPOSE_PROJECT_NAME, routing: $LC_ROUTING)
  web          $web
  lets.bible   $lb
  storybook    https://$LC_WT.storybook.localhost  (profile: storybook)
  databases    $LC_PG_DATABASE, $LC_LB_PG_DATABASE
  indices      ${OPENSEARCH_INDEX_PREFIX:-(no prefix)}*
  temporal     $TEMPORAL_NAMESPACE  (https://temporal.infra.localhost)
  valkey db    $LC_VALKEY_DB
  mail         https://mail.infra.localhost
EOF
}

cmd_temporal() {
  local tty=()
  [ -t 0 ] || tty=(-T) # hooks and background jobs have no terminal
  infra exec ${tty[@]+"${tty[@]}"} -e TEMPORAL_NAMESPACE="$TEMPORAL_NAMESPACE" temporal-admin-tools temporal "$@"
}

usage() {
  cat <<'EOF'
usage: scripts/dev-env.sh <command> [args]
  infra <compose args>   docker compose for the shared infrastructure project
  infra-up               start shared infrastructure and wait for it
  cert                   (re)issue mkcert certificates for infra + this checkout
  wt-up [clone|fresh]    provision and start this worktree's stack
  wt-down                stop this worktree and delete its databases, indices,
                         Temporal namespace, cache, and certificate
  wt-info                print this checkout's URLs and resource names
  temporal <args>        Temporal CLI in this checkout's namespace
EOF
}

command=${1:-}
[ $# -gt 0 ] && shift
case "$command" in
  infra) infra "$@" ;;
  infra-up) cmd_infra_up "$@" ;;
  cert) cmd_cert ;;
  wt-up) cmd_wt_up "$@" ;;
  wt-down) cmd_wt_down ;;
  wt-info) cmd_wt_info ;;
  temporal) cmd_temporal "$@" ;;
  *) usage; [ -z "$command" ] || exit 1 ;;
esac
