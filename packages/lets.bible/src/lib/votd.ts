function gcd(a: number, b: number): number {
  while (b !== 0) {
    [a, b] = [b, a % b];
  }
  return a;
}

// A stride coprime to the list length makes `(day * stride) % length` a full-period
// walk: each day moves to a new verse and every verse is shown exactly once before
// any repeats — even coverage, deterministic per day, in a varied (non-sequential)
// order. The golden-ratio stride spreads consecutive days far apart in the list;
// we step down to the nearest value coprime to the length so the period is full.
const STRIDE = (() => {
  const n = VOTD_REFS.length;
  let s = Math.max(1, Math.round(n * 0.618_033_988_75));
  while (n > 1 && gcd(s, n) !== 1) {
    s -= 1;
  }
  return s;
})();

// Whole UTC days since the Unix epoch — the rotation key. Everyone sees the same
// verse on a given calendar day (UTC), and SSR matches the client.
export function epochDay(now: number): number {
  return Math.floor(now / 86_400_000);
}

// The ref to show on the given epoch-day. Pure + deterministic.
export function votdRefForDay(day: number): string {
  const n = VOTD_REFS.length;
  const idx = (((day * STRIDE) % n) + n) % n;
  return VOTD_REFS[idx] ?? VOTD_REFS[0];
}
